#Requires -Version 7.4
[CmdletBinding()]
param([Parameter(Mandatory)][string]$Root)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$Root = [IO.Path]::GetFullPath($Root).TrimEnd('\')
$prefix = $Root + '\'
if (((Get-Item -LiteralPath $Root -Force).Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) {
    throw 'Package integrity: package root must not be a reparse point.'
}
$manifestPath = Join-Path $Root 'PackageIntegrity.json'
if (-not (Test-Path -LiteralPath $manifestPath -PathType Leaf)) { throw 'Package integrity: manifest is missing.' }
if ([IO.Path]::GetFullPath($PSCommandPath) -ne (Join-Path $Root 'tools\Test-PackageIntegrity.ps1')) {
    throw 'Package integrity: verifier must belong to the selected package.'
}
function Assert-PlainPath([string]$Path) {
    $current = $Path
    while ($current -and $current.StartsWith($prefix, [StringComparison]::OrdinalIgnoreCase)) {
        if (((Get-Item -LiteralPath $current -Force).Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) {
            throw 'Package integrity: reparse points are not supported.'
        }
        $current = Split-Path $current -Parent
    }
}
Assert-PlainPath $manifestPath
$manifest = Get-Content -LiteralPath $manifestPath -Raw | ConvertFrom-Json
if ($manifest.schemaVersion -ne 1 -or $manifest.name -ne 'ExchangeLogReportAngular' -or -not $manifest.files.Count) {
    throw 'Package integrity: unsupported or empty manifest.'
}
$seen = [Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
foreach ($entry in $manifest.files) {
    $relative = [string]$entry.path
    if (-not $relative -or $relative -match '(^[\\/]|[:/]|(^|\\)\.\.?($|\\))' -or
        [IO.Path]::IsPathFullyQualified($relative) -or $relative -in 'PackageIntegrity.json', 'FILES.sha256.json' -or
        -not $seen.Add($relative) -or [string]$entry.sha256 -notmatch '^[a-fA-F0-9]{64}$') {
        throw 'Package integrity: invalid or duplicate inventory entry.'
    }
    $path = [IO.Path]::GetFullPath((Join-Path $Root $relative))
    if ([IO.Path]::GetRelativePath($Root, $path) -cne $relative -or
        -not $path.StartsWith($prefix, [StringComparison]::OrdinalIgnoreCase) -or
        -not (Test-Path -LiteralPath $path -PathType Leaf)) { throw "Package integrity: missing file $relative" }
    Assert-PlainPath $path
    $file = Get-Item -LiteralPath $path
    if ($file.Length -ne $entry.bytes -or (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash -ne $entry.sha256) {
        throw "Package integrity: bytes or SHA256 mismatch for $relative"
    }
}
foreach ($required in @('tools\Test-PackageIntegrity.ps1', 'collector\Invoke-ExchangeLogReport.ps1',
    'collector\ExchangeLogReport.psm1', 'web\index.html', 'powershell\pwsh.exe')) {
    if (-not $seen.Contains($required)) { throw "Package integrity: required file is not protected: $required" }
}
$mutable = 'collector\config\ExchangeLogReport.config.psd1'
$generated = @('collector\bin\', 'collector\data\', 'collector\logs\', 'collector\reports\', 'data\', 'logs\', 'reports\')
foreach ($file in Get-ChildItem -LiteralPath $Root -File -Recurse -Force) {
    $relative = $file.FullName.Substring($prefix.Length)
    if ($relative -in 'PackageIntegrity.json', 'FILES.sha256.json', $mutable) { continue }
    if (@($generated | Where-Object { $relative.StartsWith($_, [StringComparison]::OrdinalIgnoreCase) }).Count) { continue }
    if (-not $seen.Contains($relative)) { throw "Package integrity: unexpected immutable file $relative" }
}
[pscustomobject]@{ Name = $manifest.name; Version = $manifest.version; Files = $seen.Count; Integrity = 'Passed'; AuthenticatedPublisher = $false }

